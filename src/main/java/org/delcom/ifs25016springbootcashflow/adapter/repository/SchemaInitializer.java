package org.delcom.ifs25016springbootcashflow.adapter.repository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/** Membuat tabel users dan transactions bila belum ada (idempotent). */
public final class SchemaInitializer {
    private static final String USERS = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(100) NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                full_name VARCHAR(200) NOT NULL,
                role VARCHAR(20) NOT NULL,
                photo_path VARCHAR(500)
            )""";
    private static final String TRANSACTIONS = """
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL,
                description TEXT NOT NULL,
                amount BIGINT NOT NULL,
                type VARCHAR(20) NOT NULL,
                proof_path VARCHAR(500),
                created_at TIMESTAMP NOT NULL,
                CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id)
            )""";

    private SchemaInitializer() {
    }

    public static void initialize(DataSource dataSource) {
        try (Connection c = dataSource.getConnection(); Statement st = c.createStatement()) {
            st.execute(USERS);
            st.execute(TRANSACTIONS);
        } catch (SQLException ex) {
            throw new RepositoryException("Gagal membuat skema database", ex);
        }
    }
}
